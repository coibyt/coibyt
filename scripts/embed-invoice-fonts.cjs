// Regenerates src/lib/invoice-font-data.ts from the .ttf files in
// src/assets/fonts. Run this after replacing/adding a font there:
//   node scripts/embed-invoice-fonts.cjs
//
// The fonts are embedded as base64 strings directly in the JS bundle
// (rather than read from disk at runtime via fs) so invoice PDF generation
// never depends on those loose binary files surviving whatever a host's
// deploy pipeline does with the repo (see src/lib/invoices.ts).
const fs = require("fs");
const path = require("path");

const FONT_DIR = path.join(__dirname, "..", "src", "assets", "fonts");
const OUT_FILE = path.join(__dirname, "..", "src", "lib", "invoice-font-data.ts");

const files = {
  NOTO_SANS_REGULAR: "NotoSans-Regular.ttf",
  NOTO_SANS_BOLD: "NotoSans-Bold.ttf",
  NOTO_SANS_THAI_REGULAR: "NotoSansThai-Regular.ttf",
  NOTO_SANS_THAI_BOLD: "NotoSansThai-Bold.ttf",
  NOTO_SANS_KHMER_REGULAR: "NotoSansKhmer-Regular.ttf",
  NOTO_SANS_KHMER_BOLD: "NotoSansKhmer-Bold.ttf",
};

let out =
  "// Auto-generated by scripts/embed-invoice-fonts.cjs — base64-embedded invoice PDF fonts.\n" +
  "// Embedded directly in the JS bundle (not read from disk at runtime) so\n" +
  "// the PDF route never depends on loose font files surviving deployment.\n" +
  "// Regenerate with: node scripts/embed-invoice-fonts.cjs\n\n";

for (const [key, file] of Object.entries(files)) {
  const buf = fs.readFileSync(path.join(FONT_DIR, file));
  out += `export const ${key}_B64 =\n  "${buf.toString("base64")}";\n\n`;
}

fs.writeFileSync(OUT_FILE, out);
console.log(`Wrote ${OUT_FILE} (${(out.length / 1024 / 1024).toFixed(2)} MB)`);
