// Rebuilds src/content/wiki/<locale>/index.ts from the article files beside it
// (one file per Academy lesson: <lesson-slug>.ts with a default export).
//   node scripts/wiki-index.mjs
// Also checks what a typo would break: duplicate slugs, a slug that collides with a
// chapter slug, missing pictures, and meta text that is too long for search results.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const NAMES = { vi: "VI_ARTICLES", en: "EN_ARTICLES", fi: "FI_ARTICLES" };
const ident = (file) => "a_" + file.replace(/\.ts$/, "").replace(/[^a-zA-Z0-9]/g, "_");
const chapters = readFileSync(join(root, "src/lib/wiki/categories.ts"), "utf8");
let problems = 0;
const warn = (msg) => {
  problems += 1;
  console.warn("  ! " + msg);
};

for (const [locale, name] of Object.entries(NAMES)) {
  const dir = join(root, "src/content/wiki", locale);
  const files = existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => f.endsWith(".ts") && f !== "index.ts")
        .sort()
    : [];
  const slugs = new Map();
  const chapterSlugs = new Set([...chapters.matchAll(/slug: l3\("([^"]+)", "([^"]+)", "([^"]+)"\)/g)].map((m) => m[{ vi: 1, en: 2, fi: 3 }[locale]]));
  for (const f of files) {
    const src = readFileSync(join(dir, f), "utf8");
    const get = (key) => src.match(new RegExp(`\\n  ${key}:\\s*\\n?\\s*"((?:[^"\\\\]|\\\\.)*)"`))?.[1];
    const slug = get("slug");
    const lesson = get("lesson");
    if (!slug) warn(`${locale}/${f}: no slug`);
    if (lesson !== f.replace(/\.ts$/, "")) warn(`${locale}/${f}: lesson "${lesson}" does not match the file name`);
    if (get("locale") !== locale) warn(`${locale}/${f}: locale is "${get("locale")}"`);
    if (slugs.has(slug)) warn(`${locale}/${f}: slug "${slug}" is also used by ${slugs.get(slug)}`);
    if (chapterSlugs.has(slug)) warn(`${locale}/${f}: slug "${slug}" is a chapter slug`);
    slugs.set(slug, f);
    const title = get("metaTitle") ?? "";
    const desc = get("metaDescription") ?? "";
    if (title.length > 65) warn(`${locale}/${f}: metaTitle is ${title.length} characters (keep it to about 60)`);
    if (desc.length < 120 || desc.length > 165) warn(`${locale}/${f}: metaDescription is ${desc.length} characters (aim for 140–158)`);
    // Pictures: the folder helper `img("name")` plus any literal /wiki/… path.
    const folder = src.match(/const img = \(name: string\) => `([^$`]+)\$\{name\}([^`]*)`/);
    const pics = [...src.matchAll(/"(\/wiki\/[^"]+)"/g)].map((m) => m[1]);
    if (folder) for (const m of src.matchAll(/img\("([^"]+)"\)/g)) pics.push(folder[1] + m[1] + folder[2]);
    for (const p of pics) if (!existsSync(join(root, "public", p))) warn(`${locale}/${f}: picture ${p} is missing`);
    if (!pics.length) warn(`${locale}/${f}: no pictures`);
  }
  const out = [
    "// Generated by scripts/wiki-index.mjs from the article files in this folder. Do not edit.",
    'import type { WikiArticle } from "@/lib/wiki/types";',
    ...files.map((f) => `import ${ident(f)} from "./${f.replace(/\.ts$/, "")}";`),
    "",
    `export const ${name}: WikiArticle[] = [${files.map(ident).join(", ")}];`,
    "",
  ].join("\n");
  writeFileSync(join(dir, "index.ts"), out);
  console.log(`${locale}: ${files.length} articles`);
}
if (problems) console.warn(`${problems} problem(s) to fix`);
