export type AppPageStrings = (typeof STRINGS)["en"];

export function appPageStrings(locale: string): AppPageStrings {
  return (STRINGS as Record<string, AppPageStrings>)[locale] ?? STRINGS.en;
}

/** The public install page's address in a given language. */
export function appPageUrl(locale: string, defaultLocale: string) {
  const site = process.env.NEXT_PUBLIC_SITE_URL ?? "https://varaaai.com";
  return `${site}${locale === defaultLocale ? "" : `/${locale}`}/app`;
}
