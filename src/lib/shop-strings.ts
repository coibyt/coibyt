export type ShopStrings = (typeof STRINGS)["en"];

export function shopStrings(locale: string): ShopStrings {
  return (STRINGS as Record<string, ShopStrings>)[locale] ?? STRINGS.en;
}

/** Replaces `{key}` placeholders. */
export function fill(text: string, vars: Record<string, string | number>) {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Whole-percent discount of a sale price against its regular price. */
export function discountPct(priceCents: number, compareAtCents: number | null) {
  if (!compareAtCents || compareAtCents <= priceCents) return 0;
  return Math.round((1 - priceCents / compareAtCents) * 100);
}
