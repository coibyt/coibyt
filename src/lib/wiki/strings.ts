export type WikiStrings = Strings;

export const wikiStrings = (locale: string): Strings => (locale === "vi" ? vi : locale === "fi" ? fi : en);

/** "26 tháng 11, 2026" / "26 November 2026" / "26.11.2026". */
export function wikiDate(iso: string, locale: string) {
  const d = new Date(`${iso}T12:00:00Z`);
  const tag = locale === "vi" ? "vi-VN" : locale === "fi" ? "fi-FI" : "en-GB";
  return new Intl.DateTimeFormat(tag, { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" }).format(d);
}
