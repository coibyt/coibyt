export type FanpageStrings = (typeof STRINGS)["en"];

export function fanpageStrings(locale: string): FanpageStrings {
  return (STRINGS as Record<string, FanpageStrings>)[locale] ?? STRINGS.en;
}

export const POST_TAGS = ["PROMO", "NEW_WORK", "NEWS", "TIP"] as const;
export type PostTag = (typeof POST_TAGS)[number];
export const POST_CTAS = ["BOOK", "SHOP", "CALL"] as const;
export type PostCta = (typeof POST_CTAS)[number];
export const MAX_POST_IMAGES = 6;

export function isPostTag(v: unknown): v is PostTag {
  return typeof v === "string" && (POST_TAGS as readonly string[]).includes(v);
}
export function isPostCta(v: unknown): v is PostCta {
  return typeof v === "string" && (POST_CTAS as readonly string[]).includes(v);
}

/** "3 hours ago" in the viewer's language, or "Just now". */
export function timeAgo(iso: string, locale: string, justNow: string) {
  const diff = (new Date(iso).getTime() - Date.now()) / 1000;
  const abs = Math.abs(diff);
  if (abs < 60) return justNow;
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: "auto" });
  const units: [Intl.RelativeTimeFormatUnit, number][] = [
    ["minute", 60],
    ["hour", 3600],
    ["day", 86400],
    ["week", 604800],
  ];
  for (let i = units.length - 1; i >= 0; i--) {
    const [unit, sec] = units[i];
    if (abs >= sec) {
      // Older than four weeks: a plain date reads better than "9 weeks ago".
      if (unit === "week" && abs >= sec * 4) {
        return new Date(iso).toLocaleDateString(locale, { day: "numeric", month: "long", year: "numeric" });
      }
      return rtf.format(Math.round(diff / sec), unit);
    }
  }
  return justNow;
}
