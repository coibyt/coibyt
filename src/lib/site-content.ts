/** These top-level `/site/*` pages live outside the `[locale]` segment (so
 * they can skip the platform's own navbar/footer for a clean, salon-branded
 * page — same reasoning as /embed), so next-intl's Link can't be used to
 * build hrefs. This mirrors routing.localePrefix ("as-needed": the default
 * locale has no prefix, every other one does). */
export function sitePrefix(locale: string): string {
  return locale === routing.defaultLocale ? "" : `/${locale}`;
}

export function siteStrings(locale: string): SiteStrings {
  return SITE_STRINGS[locale] ?? SITE_STRINGS.en;
}
