import type { Metadata } from "next";
import QRCode from "qrcode";
import { ArrowRight, BellRing, CalendarCheck, Check, Megaphone, RefreshCw, Smartphone, Apple } from "lucide-react";
import { Link } from "@/i18n/navigation";
import { routing } from "@/i18n/routing";
import { appPageStrings, appPageUrl } from "@/lib/app-page-strings";
import { spotlightStrings } from "@/lib/business-landing/spotlight";
import { AppInstallHero } from "@/components/app-install-hero";
import { FooterAppDownload } from "@/components/footer-app-download";

export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params;
  const S = appPageStrings(locale);
  return {
    title: S.metaTitle,
    description: S.metaDescription,
    openGraph: { title: S.metaTitle, description: S.metaDescription, images: ["/icons/icon-512.png"] },
  };
}

const FEATURE_ICONS = [CalendarCheck, BellRing, Megaphone, RefreshCw];

export default async function AppPage({ params }: { params: Promise<{ locale: string }> }) {
  const { locale } = await params;
  const S = appPageStrings(locale);
  const app = spotlightStrings(locale).footer;
  // Generated by us from our own URL, so it's safe to inline.
  const qrSvg = await QRCode.toString(appPageUrl(locale, routing.defaultLocale), {
    type: "svg",
    margin: 0,
    errorCorrectionLevel: "M",
    color: { dark: "#1f182d", light: "#ffffff" },
  });

  return (
    <div className="bg-mist-50">
      {/* Hero */}
      <section className="relative overflow-hidden bg-gradient-to-b from-primary-50 via-white to-mist-50">
        <div className="pointer-events-none absolute -left-32 -top-32 h-96 w-96 rounded-full bg-primary-200/50 blur-3xl" />
        <div className="pointer-events-none absolute -right-24 top-20 h-80 w-80 rounded-full bg-peach-200/60 blur-3xl" />
        <div className="container relative max-w-3xl py-14 text-center sm:py-20">
          <div className="relative mx-auto h-28 w-28 sm:h-32 sm:w-32">
            <span className="absolute inset-0 animate-pulse rounded-[2rem] bg-primary-400/30 blur-2xl" />
            <span className="relative flex h-full w-full items-center justify-center rounded-[2rem] bg-white shadow-[0_24px_50px_-18px_rgba(98,79,137,0.7)] ring-1 ring-primary-100">
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img src="/icons/icon-192.png" alt="VaraaAi" className="h-20 w-20 rounded-[1.4rem] sm:h-24 sm:w-24" />
            </span>
          </div>
          <p className="mt-7 inline-flex items-center gap-1.5 rounded-full bg-white px-3 py-1 text-[11px] font-bold uppercase tracking-[0.16em] text-primary-600 ring-1 ring-primary-100">
            <Smartphone className="h-3.5 w-3.5" />
            {S.eyebrow}
          </p>
          <h1 className="mt-4 text-4xl font-extrabold tracking-tight text-ink-900 sm:text-5xl">{S.title}</h1>
          <p className="mx-auto mt-4 max-w-xl text-base leading-relaxed text-ink-700 sm:text-lg">{S.lead}</p>

          <div className="mt-9">
            <AppInstallHero locale={locale} />
          </div>

          <ul className="mt-7 flex flex-wrap justify-center gap-2">
            {[S.free, S.size, S.noStore].map((perk) => (
              <li key={perk} className="inline-flex items-center gap-1.5 rounded-full bg-white px-3 py-1 text-xs font-semibold text-ink-700 ring-1 ring-ink-100">
                <Check className="h-3.5 w-3.5 text-emerald-500" />
                {perk}
              </li>
            ))}
          </ul>

          <div className="mt-10 border-t border-ink-100 pt-8">
            <p className="mb-4 text-xs font-bold uppercase tracking-[0.16em] text-ink-400">{S.otherDevices}</p>
            <div className="flex justify-center">
              <FooterAppDownload
                labels={{
                  title: app.title,
                  installOn: app.installOn,
                  desktop: app.desktop,
                  installed: app.installed,
                  iosHint: app.iosHint,
                  otherHint: app.otherHint,
                }}
              />
            </div>
          </div>
        </div>
      </section>

      {/* Steps */}
      <section className="container max-w-5xl py-14">
        <h2 className="text-center text-2xl font-extrabold tracking-tight text-ink-900 sm:text-3xl">{S.stepsTitle}</h2>
        <div className="mt-8 grid gap-5 md:grid-cols-2">
          {(
            [
              [S.android, Smartphone, S.androidSteps, "from-emerald-500 to-teal-500"],
              [S.iphone, Apple, S.iphoneSteps, "from-ink-700 to-ink-900"],
            ] as const
          ).map(([title, Icon, steps, tone]) => (
            <div key={title} className="rounded-3xl bg-white p-6 shadow-card ring-1 ring-ink-100 sm:p-7">
              <p className="flex items-center gap-3 text-lg font-bold text-ink-900">
                <span className={`flex h-10 w-10 items-center justify-center rounded-2xl bg-gradient-to-br text-white ${tone}`}>
                  <Icon className="h-5 w-5" />
                </span>
                {title}
              </p>
              <ol className="mt-5 space-y-4">
                {steps.map((step, i) => (
                  <li key={i} className="flex gap-3">
                    <span className="flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-primary-50 text-xs font-bold text-primary-600 ring-1 ring-primary-100">
                      {i + 1}
                    </span>
                    <span className="pt-0.5 text-sm leading-relaxed text-ink-700">{step}</span>
                  </li>
                ))}
              </ol>
            </div>
          ))}
        </div>
      </section>

      {/* Features + QR */}
      <section className="container max-w-5xl pb-16">
        <h2 className="text-center text-2xl font-extrabold tracking-tight text-ink-900 sm:text-3xl">{S.featuresTitle}</h2>
        <div className="mt-8 grid gap-5 lg:grid-cols-[minmax(0,1fr)_17rem]">
          <div className="grid gap-4 sm:grid-cols-2">
            {S.features.map(([title, text], i) => {
              const Icon = FEATURE_ICONS[i];
              return (
                <div key={title} className="rounded-3xl bg-white p-5 shadow-card ring-1 ring-ink-100">
                  <span className="flex h-11 w-11 items-center justify-center rounded-2xl bg-primary-50 text-primary-600">
                    <Icon className="h-5 w-5" />
                  </span>
                  <p className="mt-4 font-bold text-ink-900">{title}</p>
                  <p className="mt-1 text-sm leading-relaxed text-ink-700">{text}</p>
                </div>
              );
            })}
          </div>
          <div className="flex flex-col items-center justify-center rounded-3xl bg-[#1a1326] p-6 text-center text-white">
            <p className="font-bold">{S.scanTitle}</p>
            <div className="mt-4 rounded-2xl bg-white p-3">
              <div className="h-36 w-36 [&_svg]:h-full [&_svg]:w-full" dangerouslySetInnerHTML={{ __html: qrSvg }} />
            </div>
            <p className="mt-4 text-xs leading-relaxed text-white/70">{S.scanText}</p>
          </div>
        </div>

        <div className="mt-10 flex flex-col items-center justify-center gap-3 sm:flex-row">
          <Link href="/" className="inline-flex items-center gap-2 rounded-full bg-white px-5 py-3 text-sm font-semibold text-ink-900 ring-1 ring-ink-100 hover:ring-ink-400">
            {S.about}
            <ArrowRight className="h-4 w-4" />
          </Link>
          <Link href="/business" className="inline-flex items-center gap-2 rounded-full px-5 py-3 text-sm font-semibold text-primary-600 hover:underline">
            {S.forSalons}
          </Link>
        </div>
      </section>
    </div>
  );
}
