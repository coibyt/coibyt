import { getLocale, getTranslations } from "next-intl/server";
import { Link } from "@/i18n/navigation";
import { priceListNavLabel } from "@/lib/price-list/i18n/nav-label";
import { posterNavLabel } from "@/lib/qr-poster/i18n/nav-label";
import { supportCenterStrings } from "@/lib/support-ai/strings";
import { spotlightStrings } from "@/lib/business-landing/spotlight";
import QRCode from "qrcode";
import { BellRing, Check, Sparkles } from "lucide-react";
import { FooterAppDownload } from "@/components/footer-app-download";

export async function Footer() {
  const [t, locale] = await Promise.all([getTranslations("footer"), getLocale()]);
  const year = new Date().getFullYear();
  const spot = spotlightStrings(locale);
  const app = spot.footer;
  const alarmTitle = spot.alarm.mockTitle;
  const site = process.env.NEXT_PUBLIC_SITE_URL ?? "https://varaaai.com";
  // Generated by us from our own URL, so it's safe to inline.
  const qrSvg = await QRCode.toString(`${site}${locale === "vi" ? "" : `/${locale}`}`, {
    type: "svg",
    margin: 0,
    errorCorrectionLevel: "M",
    color: { dark: "#1f182d", light: "#ffffff" },
  });

  return (
    <footer className="border-t border-ink-100 bg-mist-50">
      <div className="container pt-12">
        <div className="relative overflow-hidden rounded-[2rem] bg-gradient-to-br from-white via-primary-50/70 to-peach-50 p-6 shadow-[0_24px_60px_-28px_rgba(64,50,92,0.35)] ring-1 ring-primary-100 sm:p-8 lg:p-10">
          <div className="pointer-events-none absolute -right-24 -top-24 h-72 w-72 rounded-full bg-primary-200/40 blur-3xl" />
          <div className="pointer-events-none absolute -bottom-28 left-1/3 h-64 w-64 rounded-full bg-peach-200/50 blur-3xl" />
          <div className="relative grid items-center gap-8 md:grid-cols-[minmax(0,1fr)_auto]">
            <div className="text-center sm:text-left">
              <div className="flex flex-col items-center gap-4 sm:flex-row sm:items-center">
                <span className="flex h-16 w-16 shrink-0 items-center justify-center rounded-[1.25rem] bg-white shadow-[0_12px_28px_-10px_rgba(98,79,137,0.55)] ring-1 ring-primary-100">
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img src="/icons/icon-192.png" alt="" className="h-12 w-12 rounded-2xl" />
                </span>
                <div>
                  <p className="inline-flex items-center gap-1.5 rounded-full bg-white/80 px-2.5 py-0.5 text-[11px] font-bold uppercase tracking-[0.16em] text-primary-600 ring-1 ring-primary-100">
                    <Sparkles className="h-3 w-3" />
                    {app.eyebrow}
                  </p>
                  <p className="mt-1.5 text-2xl font-extrabold tracking-tight text-ink-900 sm:text-[1.7rem]">{app.title}</p>
                </div>
              </div>
              <p className="mt-3 max-w-xl text-sm leading-relaxed text-ink-700 sm:text-base">{app.body}</p>
              <ul className="mt-4 flex flex-wrap justify-center gap-2 sm:justify-start">
                {app.perks.map((perk) => (
                  <li key={perk} className="inline-flex items-center gap-1.5 rounded-full bg-white px-3 py-1 text-xs font-semibold text-ink-700 ring-1 ring-ink-100">
                    <Check className="h-3.5 w-3.5 text-emerald-500" />
                    {perk}
                  </li>
                ))}
              </ul>
              <div className="mt-6">
                <FooterAppDownload
                  labels={{
                    title: app.title,
                    installOn: app.installOn,
                    desktop: app.desktop,
                    installed: app.installed,
                    iosHint: app.iosHint,
                    otherHint: app.otherHint,
                  }}
                />
              </div>
            </div>

            <div className="hidden items-center gap-6 md:flex" aria-hidden>
              <div className="relative">
                <div className="w-40 rotate-[-6deg] rounded-[2rem] bg-ink-900 p-1.5 shadow-[0_30px_50px_-20px_rgba(31,24,45,0.6)]">
                  <div className="h-72 overflow-hidden rounded-[1.6rem] bg-gradient-to-b from-primary-700 via-primary-500 to-peach-200 p-3">
                    <div className="mx-auto h-1 w-10 rounded-full bg-white/40" />
                    <div className="mt-4 rounded-2xl bg-white/95 p-2.5 shadow-lg">
                      <div className="flex items-center gap-1.5">
                        {/* eslint-disable-next-line @next/next/no-img-element */}
                        <img src="/icons/icon-192.png" alt="" className="h-4 w-4 rounded" />
                        <span className="text-[8px] font-bold text-ink-400">VaraaAi</span>
                      </div>
                      <p className="mt-1 flex items-center gap-1 text-[10px] font-extrabold text-ink-900">
                        <BellRing className="h-3 w-3 text-coral-500" />
                        {alarmTitle}
                      </p>
                      <p className="text-[9px] text-ink-700">14:00 · Anna</p>
                    </div>
                    <div className="mt-6 grid grid-cols-3 gap-2.5 px-1">
                      {[0, 1, 2, 3, 4, 5].map((i) => (
                        <span key={i} className={`aspect-square rounded-xl ${i === 0 ? "bg-white shadow" : "bg-white/25"}`}>
                          {i === 0 && (
                            // eslint-disable-next-line @next/next/no-img-element
                            <img src="/icons/icon-192.png" alt="" className="h-full w-full rounded-xl" />
                          )}
                        </span>
                      ))}
                    </div>
                  </div>
                </div>
              </div>
              <div className="hidden w-36 flex-col items-center rounded-3xl bg-white p-4 text-center shadow-card ring-1 ring-primary-100 lg:flex">
                <div className="h-28 w-28 [&_svg]:h-full [&_svg]:w-full" dangerouslySetInnerHTML={{ __html: qrSvg }} />
                <p className="mt-2.5 text-[11px] font-semibold leading-snug text-ink-700">{app.scan}</p>
              </div>
            </div>
          </div>
        </div>
      </div>
      <div className="container grid gap-8 py-12 sm:grid-cols-2 lg:grid-cols-4">
        <div>
          <span className="text-lg font-extrabold text-primary-500">
            Varaa<span className="text-ink-900">Ai</span>
          </span>
          <p className="mt-3 max-w-xs text-sm text-ink-400">{t("tagline")}</p>
        </div>
        <FooterColumn
          title={t("forCustomers")}
          links={[
            { href: "/", label: t("forCustomers") },
            { href: "/account/bookings", label: "" },
          ].filter((l) => l.label)}
        />
        <FooterColumn
          title={t("forBusiness")}
          links={[
            { href: "/business", label: t("forBusiness") },
            { href: "/salon-check", label: locale === "vi" ? "Kiểm tra salon miễn phí" : "Free salon check" },
            { href: "/tools/price-list", label: priceListNavLabel(locale) },
            { href: "/tools/qr-poster", label: posterNavLabel(locale) },
          ]}
        />
        <FooterColumn
          title={t("company")}
          links={[
            { href: "/", label: "VaraaAi.Com" },
            { href: "/support", label: supportCenterStrings(locale).eyebrow },
            { href: "/terms", label: t("terms") },
            { href: "/privacy", label: locale === "vi" ? "Chính sách bảo mật" : "Privacy Policy" },
          ]}
        />
      </div>
      <div className="border-t border-ink-100 py-4 text-center text-xs text-ink-400">
        © {year} VaraaAi.Com — {t("rights")}
      </div>
    </footer>
  );
}

function FooterColumn({
  title,
  links,
}: {
  title: string;
  links: { href: string; label: string }[];
}) {
  return (
    <div>
      <h4 className="mb-3 text-sm font-semibold text-ink-900">{title}</h4>
      <ul className="space-y-2 text-sm text-ink-400">
        {links.map((l) => (
          <li key={l.href}>
            <Link href={l.href} className="hover:text-ink-900">
              {l.label}
            </Link>
          </li>
        ))}
      </ul>
    </div>
  );
}
